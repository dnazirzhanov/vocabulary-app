@dataclass(frozen=True)
class VocabularyResult:
    word_count: int
    unique_lemmas: int
    cefr_distribution: dict[str, int]  # {"A1": n, "A2": n, ...}
    score: float  # 0–100
    raw: dict[str, object]


def meets_minimum_evidence(word_count: int) -> bool:
    return word_count >= MIN_WORDS_FOR_VOCABULARY


def compute_vocabulary(transcript: str) -> VocabularyResult:
    """Lemmatise the transcript and score vocabulary breadth and depth."""
    nlp = _get_nlp()
    doc = nlp(transcript.lower())

    content_lemmas: list[str] = []
    for token in doc:
        if (
            token.pos_ in _CONTENT_POS
            and not token.is_stop
            and not token.is_punct
            and token.is_alpha
            and len(token.lemma_) > 2
            and token.lemma_ not in _STOPLEMMAS
        ):
            content_lemmas.append(token.lemma_)

    if not content_lemmas:
        return VocabularyResult(
            word_count=0,
            unique_lemmas=0,
            cefr_distribution={},
            score=0.0,
            raw={"note": "no_content_words"},
        )

    # CEFR distribution
    dist: dict[str, int] = {}
    for lemma in content_lemmas:
        level = _CEFR.get(lemma, "C1")  # unknown → treated as advanced
        dist[level] = dist.get(level, 0) + 1

    # Weighted average CEFR level (higher = better for scoring)
    total = sum(dist.values())
    level_sum = sum(_LEVEL_SCORE.get(lvl, 80) * count for lvl, count in dist.items())
    avg_level_score = level_sum / total if total > 0 else 0

    # Lexical diversity: unique lemmas / total content words, max at 0.6+
    unique = len(set(content_lemmas))
    diversity = min(1.0, unique / max(total * 0.6, 1))
    diversity_score = diversity * 100

    # Combined score: 60% CEFR level, 40% diversity
    score = (avg_level_score * 0.6) + (diversity_score * 0.4)

    return VocabularyResult(
        word_count=total,
        unique_lemmas=unique,
        cefr_distribution=dist,
        score=round(min(100.0, score), 1),
        raw={
            "word_count": total,
            "unique_lemmas": unique,
            "cefr_distribution": dist,
            "avg_level_score": round(avg_level_score, 1),
            "diversity": round(diversity, 3),
        },
    )


# Module-level cached spaCy model (loaded once per process).
_nlp: Any = None


def _get_nlp() -> Any:
    global _nlp
    if _nlp is None:
        import spacy

        _nlp = spacy.load("en_core_web_sm", disable=["parser", "ner"])
    return _nlp
